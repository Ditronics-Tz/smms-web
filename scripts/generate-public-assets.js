const fs = require("fs");
const path = require("path");

const projectRoot = path.join(__dirname, "..");
const swOutput = path.join(projectRoot, "public", "firebase-messaging-sw.js");
const manifestOutput = path.join(projectRoot, "public", "manifest.json");
const indexHtmlPath = path.join(projectRoot, "public", "index.html");

/**
 * A value counts as configured only if it is non-empty AND is not one of the
 * placeholder strings that ship in .env.example.
 *
 * This has to match the same rule the app uses in src/firebase/firebase.js. If
 * the generator thought Firebase was enabled while the bundle did not (or the
 * other way round) the service worker on disk would not match the code trying to
 * register it, which is what produced "ServiceWorker script evaluation failed".
 */
const PLACEHOLDER_PATTERN = /^(your[_-]|changeme|placeholder|example[._-]|xxx|todo|tbd)/i;

const isNonEmpty = (value) => {
  if (value === undefined || value === null || value === "") return false;
  return !PLACEHOLDER_PATTERN.test(String(value).trim());
};

function loadEnvFile(file) {
  const fullPath = path.join(projectRoot, file);
  if (!fs.existsSync(fullPath)) {
    return {};
  }
  const env = {};
  const lines = fs.readFileSync(fullPath, "utf8").split(/\r?\n/);
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }
    const eq = line.indexOf("=");
    if (eq === -1) {
      continue;
    }
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

const lifecycle = process.env.npm_lifecycle_event || "";
const isBuild = lifecycle.includes("build");
const modeName = isBuild ? "production" : "development";

// Same precedence CRA uses, so the generated assets and the bundle agree.
// Previously only .env and .env.<mode> were read, so a developer who put their
// Firebase vars in .env.local got a bundle that tried to register a service
// worker while the generator had written the inert one.
const env = {
  ...loadEnvFile(".env"),
  ...loadEnvFile(".env.local"),
  ...loadEnvFile(`.env.${modeName}`),
  ...loadEnvFile(`.env.${modeName}.local`),
  ...process.env,
};

const defaults = {
  APP_NAME: "Meal Management System",
  APP_SHORT_NAME: "MMS",
  APP_DESCRIPTION: "Meal management platform for schools and cafeterias",
  PRIMARY_COLOR: "#FFA500",
  FAVICON_PATH: "",
};

const branding = {
  APP_NAME: isNonEmpty(env.REACT_APP_APP_NAME) ? env.REACT_APP_APP_NAME : defaults.APP_NAME,
  APP_SHORT_NAME: isNonEmpty(env.REACT_APP_APP_SHORT_NAME)
    ? env.REACT_APP_APP_SHORT_NAME
    : defaults.APP_SHORT_NAME,
  APP_DESCRIPTION: isNonEmpty(env.REACT_APP_APP_DESCRIPTION)
    ? env.REACT_APP_APP_DESCRIPTION
    : defaults.APP_DESCRIPTION,
  PRIMARY_COLOR: isNonEmpty(env.REACT_APP_PRIMARY_COLOR) ? env.REACT_APP_PRIMARY_COLOR : defaults.PRIMARY_COLOR,
  FAVICON_PATH: isNonEmpty(env.REACT_APP_FAVICON_PATH) ? env.REACT_APP_FAVICON_PATH : defaults.FAVICON_PATH,
};

function writeIfChanged(filePath, content, label) {
  try {
    if (fs.existsSync(filePath)) {
      const current = fs.readFileSync(filePath, "utf8");
      if (current === content) {
        console.log("[generate-public-assets] " + label + " unchanged.");
        return;
      }
    }
    fs.writeFileSync(filePath, content, "utf8");
    console.log("[generate-public-assets] Wrote " + label + ".");
  } catch (error) {
    console.error("[generate-public-assets] Failed to write " + label + ":", error);
    process.exit(1);
  }
}

// ---------------------------------------------------------------------------
// 1. Firebase messaging service worker (only when Firebase env vars are present)
// ---------------------------------------------------------------------------
const firebaseConfig = {
  apiKey: env.REACT_APP_FIREBASE_API_KEY,
  authDomain: env.REACT_APP_FIREBASE_AUTH_DOMAIN,
  projectId: env.REACT_APP_FIREBASE_PROJECT_ID,
  storageBucket: env.REACT_APP_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.REACT_APP_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.REACT_APP_FIREBASE_APP_ID,
};

const firebaseEnabled =
  Object.values(firebaseConfig).every((value) => isNonEmpty(value)) &&
  isNonEmpty(env.REACT_APP_VAPID_KEY);

const enabledSw = `// This file is regenerated by scripts/generate-public-assets.js (npm prestart/prebuild)
// from REACT_APP_FIREBASE_* and REACT_APP_VAPID_KEY. Never commit credentials here.
//
// The whole worker body is defensive on purpose: a service worker that throws
// while being evaluated is reported by the browser as
// "ServiceWorker script evaluation failed", and a blocked or offline CDN is not
// something the app should fail on. If Firebase cannot be loaded we simply stay
// inert instead of breaking the page.
let messaging = null;

try {
  self.__smmsFirebase = {
    config: ${JSON.stringify(firebaseConfig)},
  };
  importScripts("https://www.gstatic.com/firebasejs/10.8.1/firebase-app-compat.js");
  importScripts("https://www.gstatic.com/firebasejs/10.8.1/firebase-messaging-compat.js");

  if (self.firebase && typeof self.firebase.initializeApp === "function") {
    if (!self.firebase.apps || self.firebase.apps.length === 0) {
      self.firebase.initializeApp(self.__smmsFirebase.config);
    }
    messaging = self.firebase.messaging();
  }
} catch (error) {
  // Leave messaging null. Evaluation must still complete.
  console.warn("[smms-sw] Firebase messaging unavailable:", error);
}

const channel = typeof BroadcastChannel !== "undefined" ? new BroadcastChannel("notification-channel") : null;

function handleBackgroundMessage(payload) {
  if (channel) {
    channel.postMessage(payload);
  }

  // Data-only messages have no \`notification\` block; showing a notification for
  // them would throw.
  const notification = (payload && payload.notification) || {};
  if (!notification.title || typeof self.registration.showNotification !== "function") {
    return;
  }

  self.registration.showNotification(notification.title, {
    body: notification.body || "",
    icon: notification.icon || "/android-chrome-192x192.png",
  });
}

if (messaging && typeof messaging.onBackgroundMessage === "function") {
  messaging.onBackgroundMessage(handleBackgroundMessage);
} else {
  self.addEventListener("push", (event) => {
    let payload = {};
    try {
      payload = event.data ? event.data.json() : {};
    } catch (error) {
      payload = {};
    }
    event.waitUntil(Promise.resolve(handleBackgroundMessage(payload)));
  });
}
`;

const noopSw = `// This file is regenerated by scripts/generate-public-assets.js (npm prestart/prebuild).
// No REACT_APP_FIREBASE_* / REACT_APP_VAPID_KEY values were found, so web push is
// disabled. This inert service worker prevents 404s and never touches Firebase.
self.addEventListener("install", (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});
`;

writeIfChanged(swOutput, firebaseEnabled ? enabledSw : noopSw, "firebase-messaging-sw.js");

// ---------------------------------------------------------------------------
// 2. Web app manifest (name / short_name / theme_color from branding env)
// ---------------------------------------------------------------------------
const manifest = {
  short_name: branding.APP_SHORT_NAME,
  name: branding.APP_NAME,
  icons: [
    {
      src: "favicon.ico",
      sizes: "64x64 32x32 24x24 16x16",
      type: "image/x-icon"
    },
    {
      src: "/android-chrome-192x192.png",
      sizes: "192x192",
      type: "image/png"
    },
    {
      src: "/android-chrome-512x512.png",
      sizes: "512x512",
      type: "image/png"
    }
  ],
  start_url: ".",
  display: "standalone",
  theme_color: branding.PRIMARY_COLOR,
  background_color: "#ffffff"
};

writeIfChanged(manifestOutput, JSON.stringify(manifest, null, 2) + "\n", "manifest.json");

// ---------------------------------------------------------------------------
// 3. index.html title / meta description / theme-color / favicon links
// ---------------------------------------------------------------------------
if (fs.existsSync(indexHtmlPath)) {
  let html = fs.readFileSync(indexHtmlPath, "utf8");
  const original = html;

  html = html.replace(/<title>[\s\S]*?<\/title>/, "<title>" + branding.APP_NAME + "</title>");
  html = html.replace(
    /<meta name="description" content="[^"]*"\s*\/>/,
    '<meta name="description" content="' + branding.APP_DESCRIPTION + '" />'
  );
  html = html.replace(
    /<meta name="theme-color" content="[^"]*"\s*\/>/,
    '<meta name="theme-color" content="' + branding.PRIMARY_COLOR + '" />'
  );
  if (isNonEmpty(branding.FAVICON_PATH)) {
    html = html.replace(
      /<link rel="icon"[^>]*>/g,
      '<link rel="icon" href="%PUBLIC_URL%/' + branding.FAVICON_PATH + '" />'
    );
  }

  if (html !== original) {
    writeIfChanged(indexHtmlPath, html, "index.html");
  } else {
    console.log("[generate-public-assets] index.html unchanged (default branding).");
  }
} else {
  console.error("[generate-public-assets] public/index.html not found; skipping HTML patch.");
}