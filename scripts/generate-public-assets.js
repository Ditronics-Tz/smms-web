const fs = require("fs");
const path = require("path");

const projectRoot = path.join(__dirname, "..");
const swOutput = path.join(projectRoot, "public", "firebase-messaging-sw.js");
const manifestOutput = path.join(projectRoot, "public", "manifest.json");
const indexHtmlPath = path.join(projectRoot, "public", "index.html");

const isNonEmpty = (value) => value !== undefined && value !== null && value !== "";

function loadEnvFile(file) {
  const fullPath = path.join(projectRoot, file);
  if (!fs.existsSync(fullPath)) {
    return {};
  }
  const env = {};
  const lines = fs.readFileSync(fullPath, "utf8").split(/\r?\n/);
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }
    const eq = line.indexOf("=");
    if (eq === -1) {
      continue;
    }
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

const lifecycle = process.env.npm_lifecycle_event || "";
const modeFile = lifecycle.includes("build") ? ".env.production" : ".env.development";
const env = { ...loadEnvFile(".env"), ...loadEnvFile(modeFile), ...process.env };

const defaults = {
  APP_NAME: "Meal Management System",
  APP_SHORT_NAME: "MMS",
  APP_DESCRIPTION: "Meal management platform for schools and cafeterias",
  PRIMARY_COLOR: "#FFA500",
  FAVICON_PATH: "",
};

const branding = {
  APP_NAME: isNonEmpty(env.REACT_APP_APP_NAME) ? env.REACT_APP_APP_NAME : defaults.APP_NAME,
  APP_SHORT_NAME: isNonEmpty(env.REACT_APP_APP_SHORT_NAME)
    ? env.REACT_APP_APP_SHORT_NAME
    : defaults.APP_SHORT_NAME,
  APP_DESCRIPTION: isNonEmpty(env.REACT_APP_APP_DESCRIPTION)
    ? env.REACT_APP_APP_DESCRIPTION
    : defaults.APP_DESCRIPTION,
  PRIMARY_COLOR: isNonEmpty(env.REACT_APP_PRIMARY_COLOR) ? env.REACT_APP_PRIMARY_COLOR : defaults.PRIMARY_COLOR,
  FAVICON_PATH: isNonEmpty(env.REACT_APP_FAVICON_PATH) ? env.REACT_APP_FAVICON_PATH : defaults.FAVICON_PATH,
};

function writeIfChanged(filePath, content, label) {
  try {
    if (fs.existsSync(filePath)) {
      const current = fs.readFileSync(filePath, "utf8");
      if (current === content) {
        console.log("[generate-public-assets] " + label + " unchanged.");
        return;
      }
    }
    fs.writeFileSync(filePath, content, "utf8");
    console.log("[generate-public-assets] Wrote " + label + ".");
  } catch (error) {
    console.error("[generate-public-assets] Failed to write " + label + ":", error);
    process.exit(1);
  }
}

// ---------------------------------------------------------------------------
// 1. Firebase messaging service worker (only when Firebase env vars are present)
// ---------------------------------------------------------------------------
const firebaseConfig = {
  apiKey: env.REACT_APP_FIREBASE_API_KEY,
  authDomain: env.REACT_APP_FIREBASE_AUTH_DOMAIN,
  projectId: env.REACT_APP_FIREBASE_PROJECT_ID,
  storageBucket: env.REACT_APP_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.REACT_APP_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.REACT_APP_FIREBASE_APP_ID,
};

const firebaseEnabled =
  Object.values(firebaseConfig).every((value) => isNonEmpty(value)) &&
  isNonEmpty(env.REACT_APP_VAPID_KEY);

const enabledSw = `importScripts("https://www.gstatic.com/firebasejs/10.8.1/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.8.1/firebase-messaging-compat.js");

// This file is regenerated by scripts/generate-public-assets.js (npm prestart/prebuild)
// from REACT_APP_FIREBASE_* and REACT_APP_VAPID_KEY. Never commit credentials here.
const firebaseConfig = {
  apiKey: ${JSON.stringify(firebaseConfig.apiKey)},
  authDomain: ${JSON.stringify(firebaseConfig.authDomain)},
  projectId: ${JSON.stringify(firebaseConfig.projectId)},
  storageBucket: ${JSON.stringify(firebaseConfig.storageBucket)},
  messagingSenderId: ${JSON.stringify(firebaseConfig.messagingSenderId)},
  appId: ${JSON.stringify(firebaseConfig.appId)},
};

firebase.initializeApp(firebaseConfig);
const messaging = firebase.messaging();

// Create a BroadcastChannel to communicate with the main window
const channel = new BroadcastChannel("notification-channel");

messaging.onBackgroundMessage((payload) => {
  console.log("Received background message ", payload);

   // Send the background message to the main window via the BroadcastChannel
  channel.postMessage(payload);

  const notificationTitle = payload.notification.title;
  const notificationOptions = {
    body: payload.notification.body,
    icon: "/android-chrome-192x192.png",
  };
  self.registration.showNotification(notificationTitle, notificationOptions);
});
`;

const noopSw = `// This file is regenerated by scripts/generate-public-assets.js (npm prestart/prebuild).
// No REACT_APP_FIREBASE_* / REACT_APP_VAPID_KEY values were found, so web push is
// disabled. This inert service worker prevents 404s and never touches Firebase.
self.addEventListener("install", (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", () => {
  // Passthrough: leave default network behavior untouched.
});
`;

writeIfChanged(swOutput, firebaseEnabled ? enabledSw : noopSw, "firebase-messaging-sw.js");

// ---------------------------------------------------------------------------
// 2. Web app manifest (name / short_name / theme_color from branding env)
// ---------------------------------------------------------------------------
const manifest = {
  short_name: branding.APP_SHORT_NAME,
  name: branding.APP_NAME,
  icons: [
    {
      src: "favicon.ico",
      sizes: "64x64 32x32 24x24 16x16",
      type: "image/x-icon"
    },
    {
      src: "/android-chrome-192x192.png",
      sizes: "192x192",
      type: "image/png"
    },
    {
      src: "/android-chrome-512x512.png",
      sizes: "512x512",
      type: "image/png"
    }
  ],
  start_url: ".",
  display: "standalone",
  theme_color: branding.PRIMARY_COLOR,
  background_color: "#ffffff"
};

writeIfChanged(manifestOutput, JSON.stringify(manifest, null, 2) + "\n", "manifest.json");

// ---------------------------------------------------------------------------
// 3. index.html title / meta description / theme-color / favicon links
// ---------------------------------------------------------------------------
if (fs.existsSync(indexHtmlPath)) {
  let html = fs.readFileSync(indexHtmlPath, "utf8");
  const original = html;

  html = html.replace(/<title>[\s\S]*?<\/title>/, "<title>" + branding.APP_NAME + "</title>");
  html = html.replace(
    /<meta name="description" content="[^"]*"\s*\/>/,
    '<meta name="description" content="' + branding.APP_DESCRIPTION + '" />'
  );
  html = html.replace(
    /<meta name="theme-color" content="[^"]*"\s*\/>/,
    '<meta name="theme-color" content="' + branding.PRIMARY_COLOR + '" />'
  );
  if (isNonEmpty(branding.FAVICON_PATH)) {
    html = html.replace(
      /<link rel="icon"[^>]*>/g,
      '<link rel="icon" href="%PUBLIC_URL%/' + branding.FAVICON_PATH + '" />'
    );
  }

  if (html !== original) {
    writeIfChanged(indexHtmlPath, html, "index.html");
  } else {
    console.log("[generate-public-assets] index.html unchanged (default branding).");
  }
} else {
  console.error("[generate-public-assets] public/index.html not found; skipping HTML patch.");
}